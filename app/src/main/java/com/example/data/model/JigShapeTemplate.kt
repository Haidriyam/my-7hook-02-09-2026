    fun getById(id: String): JigShapeTemplate {
        return shapes.find { it.shapeId.equals(id, ignoreCase = true) } ?: shapes.first()
    }

    fun getByCategory(category: JigShapeCategory): List<JigShapeTemplate> {
        if (category == JigShapeCategory.ALL) return shapes
        return shapes.filter { it.category == category }
    }
